def test_ai_summary_service_with_mock_ollama(temp_notifications_dir, sample_notifications_data, sample_important_data):
    # Write files
    daily_file = temp_notifications_dir / "notifications_2026-10-21.json"
    daily_file.write_text(json.dumps(sample_notifications_data, ensure_ascii=False), encoding="utf-8")

    important_file = temp_notifications_dir / "notificaciones_importantes.json"
    important_file.write_text(json.dumps(sample_important_data, ensure_ascii=False), encoding="utf-8")

    mock_ollama = MagicMock(spec=OllamaClient)
    mock_ollama.generate.return_value = (
        "- Se procesaron 4 notificaciones operativas.\n"
        "- Alerta bancaria crítica detectada en BBVA.\n"
        "- Se recibió 1 código de verificación de seguridad (OTP)."
    )

    service = AiSummaryService(notifications_dir=temp_notifications_dir, ollama_client=mock_ollama)
    summary = service.generate_day_summary("2026-10-21")

    assert isinstance(summary, DaySummary)
    assert summary.date == "2026-10-21"
    assert summary.total_notifications == 5
    assert summary.app_counts.get("com.whatsapp") == 2
    assert summary.app_counts.get("com.bbva.mexico") == 1
    assert summary.urgent_count >= 1
    assert summary.otp_count >= 1
    assert len(summary.urgent_and_otp_items) >= 1
    assert any("938201" in str(item.get("text")) for item in summary.urgent_and_otp_items)
    assert summary.generated_by_llm is True
    assert len(summary.highlights) == 3

    # Check saved summary file
    saved_file = temp_notifications_dir / "summary_2026-10-21.json"
    assert saved_file.exists()
    saved_data = json.loads(saved_file.read_text(encoding="utf-8"))
    assert saved_data["total_notifications"] == 5
    assert saved_data["app_counts"]["com.whatsapp"] == 2


def test_ai_summary_service_fallback_on_ollama_failure(temp_notifications_dir, sample_notifications_data):
    daily_file = temp_notifications_dir / "notifications_2026-10-21.json"
    daily_file.write_text(json.dumps(sample_notifications_data, ensure_ascii=False), encoding="utf-8")

    mock_ollama = MagicMock(spec=OllamaClient)
    mock_ollama.generate.side_effect = OllamaError("Connection refused")

    service = AiSummaryService(notifications_dir=temp_notifications_dir, ollama_client=mock_ollama)
    summary = service.generate_day_summary("2026-10-21")

    assert summary.generated_by_llm is False
    assert summary.total_notifications == 4
    assert len(summary.highlights) > 0
    # The highlights should be generated by extractive fallback
    assert any("whatsapp" in h.lower() for h in summary.highlights)

    # Saved summary should still be written
    saved_file = temp_notifications_dir / "summary_2026-10-21.json"
    assert saved_file.exists()


def test_ai_summary_service_empty_day(temp_notifications_dir):
    mock_ollama = MagicMock(spec=OllamaClient)
    service = AiSummaryService(notifications_dir=temp_notifications_dir, ollama_client=mock_ollama)

    summary = service.generate_day_summary("2026-10-22")
    assert summary.total_notifications == 0
    assert summary.urgent_count == 0
    assert summary.generated_by_llm is False
    assert len(summary.highlights) == 1
    assert "0 notificaciones" in summary.highlights[0]
    mock_ollama.generate.assert_not_called()
